const COURSE_MODULE_LANGUAGE_BY_ID = new Map();
const COURSE_MODULE_IDS_BY_LENGTH = [];
Object.entries(COURSE_MODULE_INDEX).forEach(([language, levels]) => {
    Object.values(levels).forEach(ids => ids.forEach(id => {
        COURSE_MODULE_LANGUAGE_BY_ID.set(id, language);
        COURSE_MODULE_IDS_BY_LENGTH.push(id);
    }));
});
COURSE_MODULE_IDS_BY_LENGTH.sort((a, b) => b.length - a.length || a.localeCompare(b));

function getCourseModuleIds(language, level) {
    const code = typeof normalizeLanguage === 'function' ? normalizeLanguage(language) : String(language || '');
    const normalizedLevel = String(level || '').toUpperCase();
    const ids = COURSE_MODULE_INDEX[code] && COURSE_MODULE_INDEX[code][normalizedLevel];
    return Array.isArray(ids) ? ids.slice() : [];
}

function getCourseModuleLanguage(moduleOrCardId) {
    const identity = String(moduleOrCardId && typeof moduleOrCardId === 'object'
        ? (moduleOrCardId.modId || moduleOrCardId.id || '')
        : (moduleOrCardId || '')).trim();
    if (!identity) return null;
    const exact = COURSE_MODULE_LANGUAGE_BY_ID.get(identity);
    if (exact) return exact;
    const moduleId = COURSE_MODULE_IDS_BY_LENGTH.find(id => identity.startsWith(`${id}_`));
    return moduleId ? COURSE_MODULE_LANGUAGE_BY_ID.get(moduleId) : null;
}

if (typeof window !== 'undefined') {
    window.COURSE_MODULE_INDEX = COURSE_MODULE_INDEX;
    window.getCourseModuleIds = getCourseModuleIds;
    window.getCourseModuleLanguage = getCourseModuleLanguage;
}
